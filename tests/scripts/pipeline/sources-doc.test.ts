const REFERENCE: RentReferenceInfo = {
  district: '65000200',
  reference: '65000060',
  relation: 'two-borders-away',
  secondRule: true,
  recordCount: 7,
  method: 'rent-reference-sale-ratio',
  ratio: 0.8123456,
};

function methodEntry(id: string, appliesTo: string[]): MethodEntry {
  return {
    id,
    kind: 'estimation',
    title: `Method ${id}`,
    inputs: ['test/source-a'],
    steps: ['Step one.', 'Step two.'],
    appliesTo,
    quarters: '2015Q1–2025Q4',
    setsEstimated: true,
  };
}

/** Small in-memory input: 41 districts, 3 indicators, 10 policy series; 22 of 88 houseTaxRevenue records estimated. */
function smallInput(): SourcesDocInput {
  const history: Json = validHistoryFile();
  history.sources.push({
    id: 'wiki/test-page',
    agency: 'Wikipedia contributors',
    dataset: 'Example page',
    url: 'https://en.wikipedia.org/wiki/Example',
    years: [2015, 2025],
    license: 'CC BY-SA 4.0',
    wikipedia: { title: 'Example page' },
  });
  history.indicators[0].sources.push('wiki/test-page');
  const rentSeries = history.indicators[1].series;
  rentSeries['65000010'][0] = { value: 400, estimated: true, method: 'trend-extrapolation' };

  const policy: Json = validPolicyTrackFile();
  const tax = policy.policySeries.find((s: Json) => s.id === 'houseTaxRevenue');
  for (let q = 0; q < 22; q++) {
    tax.series['Taipei'][q] = { value: 1, source: 'test/source-a', estimated: true, method: 'house-tax-even-split' };
  }
  const pass = policy.policySeries.find((s: Json) => s.id === 'commuterPassesSold');
  pass.series['Taipei'][0] = { value: 0, source: 'test/source-b', estimated: true, method: 'commuter-passes-estimate' };
  policy.methods.push(methodEntry('house-tax-even-split', ['houseTaxRevenue']));
  policy.methods.push(methodEntry('commuter-passes-estimate', ['commuterPassesSold']));
  policy.sources.push({
    id: 'test/extra',
    agency: 'Example Agency',
    dataset: 'Extra',
    url: 'https://data.example.gov.tw/extra',
    years: [2020, 2021],
    license: 'not stated',
  });

  return {
    districtsFile: validDistrictsFile(),
    historyFile: history,
    policyTrackFile: policy,
    rentReferences: [REFERENCE],
    mrtBorderNotes: ['Example Station: station point in Alpha, address in Beta'],
    mrtComparableNotes: ['Circular Example (Y01): seasonal shares of Comparable Station, nearest station by distance (1.39 km)'],
    salePriceWindowCounts: new Map([
      ['65000130', new Map([[0, 30], [3, 10], [5, 1], [10, 3]])],
      ['65000010', new Map([[0, 44]])],
    ]),
    ...TABLES,
  };
}

function lines(text: string): string[] {
  return text.split('\n');
}

describe('renderSourcesDoc', () => {
  const text = renderSourcesDoc(smallInput());

  it('starts with the generated-file notice and states the disclosure sentence', () => {
    expect(text).toContain('This file is generated by `npm run data`. Do not edit it by hand.');
    expect(text).toContain(DISCLOSURE_SENTENCE);
    expect(DISCLOSURE_SENTENCE).toBe('Initial data and events come from real open data. Policy outcomes are simulated, not predicted.');
    expect(text.indexOf('generated by')).toBeLessThan(text.indexOf('## 2.'));
  });

  it('has the nine sections in the fixed order, LF endings and exactly one trailing LF', () => {
    const headings = lines(text).filter((l) => /^## \d\. /.test(l));
    expect(headings.map((h) => h.slice(0, 5))).toEqual(['## 1.', '## 2.', '## 3.', '## 4.', '## 5.', '## 6.', '## 7.', '## 8.', '## 9.']);
    expect(text).not.toContain('\r');
    expect(text.endsWith('\n')).toBe(true);
    expect(text.endsWith('\n\n')).toBe(false);
  });

  it('describes the output format including the crash-during-commit limit', () => {
    expect(text).toContain('2-space indentation');
    expect(text).toContain('LF line endings');
    expect(text).toContain('A crash while the files are being committed');
    expect(text).toContain('- history.json rent: 1 decimals');
  });

  it('lists every source of a field under its row with id, agency, dataset, URL, years and license', () => {
    const rows = lines(text).filter((l) => l.startsWith('| rent | '));
    expect(rows).toHaveLength(2);
    for (const id of ['test/source-a', 'test/source-b']) {
      const row = rows.find((r) => r.includes(`\`${id}\``)) as string;
      expect(row).toContain('Example Agency');
      expect(row).toContain('Example dataset (Example dataset (English))');
      expect(row).toContain(`https://data.example.gov.tw/${id}?api_key=REDACTED&format=json`);
      expect(row).toContain('2015–2025');
      expect(row).toContain('Open Government Data License 1.0');
    }
    // A district field and a policy series with a record-level source outside its own list.
    expect(lines(text).some((l) => l.startsWith('| areaKm2 | km² | 2 | `test/source-a`'))).toBe(true);
    expect(lines(text).filter((l) => l.startsWith('| commuterPassesSold | ')).some((l) => l.includes('`test/source-b`'))).toBe(true);
  });

  it('writes the literal license text `not stated` for a source without a license', () => {
    expect(text).toContain('- License: not stated');
  });

  it('gives every method used by a record its own section with inputs, steps, quarters and the estimate flag', () => {
    for (const id of ['trend-extrapolation', 'house-tax-even-split', 'commuter-passes-estimate']) {
      expect(text).toContain(`### ${id}`);
    }
    const block = text.slice(text.indexOf('### trend-extrapolation'));
    expect(block).toContain('- Inputs: `test/source-a`');
    expect(block).toContain('  1. Step one.');
    expect(block).toContain('- Quarters: 2015Q1–2025Q4');
    expect(block).toContain('- Sets `estimated: true`: yes');
  });

  it('renders the Wikipedia attribution with title, URL, CC BY-SA and the reference statement', () => {
    const entry = text.slice(text.indexOf('### wiki/test-page'));
    expect(entry).toContain('- Wikipedia page: Example page');
    expect(entry).toContain('- URL: https://en.wikipedia.org/wiki/Example');
    expect(entry).toContain('CC BY-SA. Cited as a reference; no text is copied.');
  });

  it('renders the rent reference districts with ratio, method, record count and the second rule', () => {
    expect(text).toContain('| District | Reference district | Relation | Method | Rental records | Ratio | Second rule used |');
    expect(text).toContain('| District20 (65000200) | District6 (65000060) | two-borders-away |');
    expect(text).toContain('| `rent-reference-sale-ratio` | 7 | 0.8123 | yes |');
  });

  it('renders the MRT notes and the lines that are not included', () => {
    expect(text).toContain('- Example Station: station point in Alpha, address in Beta');
    expect(text).toContain('- Circular Example (Y01): seasonal shares of Comparable Station, nearest station by distance (1.39 km)');
    expect(text).toContain('(1) prefer an adjacent station on the same line');
    expect(text).toContain('(2) only when no adjacent same-line station has shares');
    expect(text).toContain('Danhai LRT, the Ankeng LRT and the Sanying Line');
    expect(text).toContain('counts only its Active_Stations');
  });

  it('renders the policy series with the estimated share, assumptions and replacement data', () => {
    const block = text.slice(text.indexOf('### houseTaxRevenue'), text.indexOf('### commuterPassPrice'));
    expect(block).toContain('- Estimated Track_Records: 22 of 88 (25.0%)');
    expect(block).toContain(POLICY_METHOD_NOTES['house-tax-even-split']!.assumption);
    expect(block).toContain(`Data that would replace the estimate: ${POLICY_METHOD_NOTES['house-tax-even-split']!.replacement}`);
    expect(block).toContain('covers all house tax, not only the tax on non-owner-occupied residential buildings');
    expect(block).toContain('concentrated in one month of the year');
    const sold = text.slice(text.indexOf('### commuterPassesSold'), text.indexOf('## 9.'));
    expect(sold).toContain('- Estimated Track_Records: 1 of 88 (1.1%)');
    expect(sold).toContain(POLICY_METHOD_NOTES['commuter-passes-estimate']!.assumption);
    expect(text).toContain('- Estimated Track_Records: 0 of 88 (0.0%)');
  });

  it('lists every row of the three committed tables with its source', () => {
    for (const r of TABLES.holdingTaxRates) {
      expect(text).toContain(`| ${r.city} | ${r.effectiveDate} | ${r.lowestRate} | ${r.highestRate} |`);
    }
    for (const r of TABLES.commuterPassProducts) {
      expect(text).toContain(`| ${r.city} | ${r.product} | ${r.effectiveDate} | ${r.priceTwd} | ${r.source} |`);
    }
    for (const r of TABLES.subleasePhases) {
      expect(text).toContain(`| ${r.city} | ${r.channel} | ${r.phase} | ${r.startDate} | ${r.totalUnits} | ${r.asOf} | ${r.source} |`);
    }
  });

  it('lists the known gaps for items 1, 2a, 2b, 3b, 4, 7 and 10 with fields, scope and Method_Id', () => {
    const section = text.slice(text.indexOf('## 9.'));
    for (const item of ['1', '2a', '2b', '3b', '4', '7', '10']) {
      expect(section).toMatch(new RegExp(`^\\| ${item} \\| `, 'm'));
    }
    expect(section).toContain('| `relativeMedianIncome`, `householdIncome` | 2024Q1–2025Q4, all 41 districts |');
    expect(section).toContain('`holding-tax-statutory-minimum`');
    for (const gap of KNOWN_GAPS) {
      for (const id of gap.methods) expect(METHOD_REGISTRY.some((m) => m.id === id)).toBe(true);
    }
  });

  it('summarises thin sale price cells per district by window radius', () => {
    expect(text).toContain('| District13 (65000130) | 30 | radius 3: 10 quarters; radius 5: 1 quarter; radius 10: 3 quarters |');
    expect(text).not.toContain('District1 (65000010) | 44');
  });

  it('contains no absolute path or drive letter, and is identical on a second render', () => {
    expect(text).not.toMatch(/[A-Za-z]:\\/);
    expect(text).not.toMatch(/data[\\/]raw/);
    expect(text).not.toMatch(/\/Users\/|\/home\//);
    expect(renderSourcesDoc(smallInput())).toBe(text);
  });
});

describe('renderSourcesDoc with missing references (Requirement 15.8)', () => {
  function detailsOf(input: SourcesDocInput): string[] {
    try {
      renderSourcesDoc(input);
    } catch (e) {
      expect(e).toBeInstanceOf(DataError);
      return [...(e as DataError).details];
    }
    throw new Error('renderSourcesDoc did not throw');
  }

  it('names a source id that has no registry entry', () => {
    const input = smallInput();
    (input.historyFile.indicators[0] as Json).sources.push('nowhere/missing');
    expect(detailsOf(input)).toContain('history.json population: source nowhere/missing is not in the source registry');
  });

  it('names a method id that has no registry entry', () => {
    const input = smallInput();
    (input.historyFile.indicators[1] as Json).series['65000020'][3] = { value: 1, estimated: true, method: 'ghost-method' };
    expect(detailsOf(input)).toContain('history.json: method ghost-method is not in the method registry');
  });

  it('names a source that lacks a required attribute', () => {
    const input = smallInput();
    (input.districtsFile.sources[0] as Json).agency = '';
    expect(detailsOf(input)).toContain('source test/source-a: agency is missing');
  });
});

describe('realistic fixture with the real registries', () => {
  const districts: Json = validDistrictsFile();
  districts.sources = [...SOURCE_REGISTRY];
  districts.methods = [...METHOD_REGISTRY];
  const input: SourcesDocInput = { ...smallInput(), districtsFile: districts };
  // The small history and policy files refer to test sources; keep them embedded next to the real ones.
  const text = renderSourcesDoc(input);

  it('passes the banned-term check with the committed lists', () => {
    const terms = parseTermList(fsCommittedReader(BANNED_TERMS_FILE));
    const exempt = parseTermList(fsCommittedReader(BANNED_TERMS_EXEMPT_FILE));
    expect(checkBannedTerms(text, terms, exempt)).toEqual([]);
  });

  it('has a note for every policy estimation method of the registry', () => {
    const policyIds = new Set(POLICY_SERIES_SPECS.map((s) => s.id));
    const policyMethods = METHOD_REGISTRY.filter((m) => m.appliesTo.some((a) => policyIds.has(a)));
    expect(policyMethods.length).toBe(Object.keys(POLICY_METHOD_NOTES).length);
    for (const m of policyMethods) expect(POLICY_METHOD_NOTES[m.id]).toBeDefined();
  });

  it('renders every registry source and method', () => {
    for (const s of SOURCE_REGISTRY) expect(text).toContain(`### ${s.id}\n`);
    for (const m of METHOD_REGISTRY) expect(text).toContain(`### ${m.id}\n`);
  });
});

describe('sourcesDocStep', () => {
  it('sets state.sourcesDoc from the files in the state and the committed tables', () => {
    const base = smallInput();
    const state = createState();
    state.districtsFile = base.districtsFile;
    state.historyFile = base.historyFile;
    state.policyTrackFile = base.policyTrackFile;
    state.rentReferences = [REFERENCE];
    const ctx = createContext({ reader: new MemoryRawReader(), logger: memoryLogger() });
    sourcesDocStep().run(ctx, state);
    expect(state.sourcesDoc).toContain(DISCLOSURE_SENTENCE);
    expect(state.sourcesDoc).toContain('| District6 (65000060) |');
  });

  it('stops with a named error when an output file is missing', () => {
    const ctx = createContext({ reader: new MemoryRawReader(), logger: memoryLogger() });
    expect(() => sourcesDocStep().run(ctx, createState())).toThrow(DataError);
  });
});
