// npm run names: writes the Chinese names of the 41 districts for the Traditional Chinese UI (play-loop
// Requirement 12.5) from the district table of the data pipeline (scripts/lib/districts.ts), whose Chinese names
// are written exactly as TOWNNAME in the MOI district boundary data (data/SOURCES.md, districts.json boundary row).
import fs from 'node:fs';
import { DISTRICTS } from './lib/districts.ts';

const OUT = 'src/ui/strings/district-names.generated.ts';

const cityZh = (city: string) => (city === 'Taipei' ? '臺北市' : '新北市');
const names = Object.fromEntries(DISTRICTS.map((d) => [d.code, d.zh.slice(cityZh(d.city).length)]));
const text = `// Generated by \`npm run names\` (scripts/build-names.ts). Do not edit by hand.
// Source: TOWNNAME of the MOI district boundary data, as recorded in scripts/lib/districts.ts.

/** Chinese district name by District_Code (without the city). */
export const DISTRICT_NAMES_ZH: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};

/** Chinese city names. */
export const CITY_NAMES_ZH: Readonly<Record<string, string>> = { Taipei: '臺北市', 'New Taipei': '新北市' };
`;
fs.writeFileSync(OUT, text);
console.log(`npm run names: ${Object.keys(names).length} districts → ${OUT}`);
