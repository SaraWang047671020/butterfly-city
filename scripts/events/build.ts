/**
 * Event build (event-library Requirements 4.5, 6.5 to 6.8, 8.1 to 8.3, 8.7): load the curated table, check it,
 * derive the cards, validate the output, then write public/data/events.json and data/EVENT-SOURCES.md in one
 * transactional write. Any error writes nothing.
 */
import path from 'node:path';
import { validateEventsFile } from '../../src/data/validate-events.ts';
import type { EventCard, EventsFile } from '../../src/types/events-file.ts';
import { ROOT } from '../lib/paths.ts';
import { BANNED_TERMS_EXEMPT_FILE, BANNED_TERMS_FILE, checkBannedTerms, parseTermList } from '../pipeline/banned-terms.ts';
import { serializeJson } from '../pipeline/serialize.ts';
import { nodeFs, writeAll, type WriteFs } from '../pipeline/write.ts';
import { deriveCard, RateMismatchError, sortCards } from './derive.ts';
import { DISCOUNT_RATE_FILE, parseDiscountRateCsv, type RateRow } from './discount-rate.ts';
import { checkTable, ROWS_FILE, TABLE_FILE, type EventsTable, type SourceRowsFile } from './table.ts';
import { checkCardText, checkCardTextZh, EVENT_BANNED_TERMS_FILE } from './text-checks.ts';

export const EVENTS_OUT = 'public/data/events.json';
export const EVENT_SOURCES_OUT = 'data/EVENT-SOURCES.md';

/** Reads a repository file as text, or returns undefined when it does not exist. */
export type ReadText = (repoPath: string) => string | undefined;

export interface BuildResult {
  readonly ok: boolean;
  readonly errors: readonly string[];
  readonly cards: readonly EventCard[];
  readonly files: { readonly events: string; readonly sources: string } | undefined;
}

function parseJson<T>(read: ReadText, file: string, errors: string[]): T | undefined {
  const text = read(file);
  if (text === undefined) {
    errors.push(`${file}: file not found`);
    return undefined;
  }
  try {
    return JSON.parse(text) as T;
  } catch (e) {
    errors.push(`${file}: not valid JSON (${e instanceof Error ? e.message : String(e)})`);
    return undefined;
  }
}

const LICENSE_NOT_STATED = 'not stated';

/** data/EVENT-SOURCES.md: one row per distinct source URL, with the years of the cards that use it. */
export function renderEventSources(cards: readonly EventCard[]): string {
  const bySource = new Map<string, { publisher: string; label: string; url: string; years: Set<string> }>();
  for (const c of cards) {
    for (const s of c.sources) {
      const entry = bySource.get(s.url) ?? { publisher: s.publisher, label: s.label, url: s.url, years: new Set<string>() };
      entry.years.add(c.date.slice(0, 4));
      bySource.set(s.url, entry);
    }
  }
  const esc = (t: string): string => t.replace(/\|/g, '\\|');
  const rows = [...bySource.values()].sort((a, b) =>
    a.publisher === b.publisher ? (a.url < b.url ? -1 : 1) : a.publisher < b.publisher ? -1 : 1,
  );
  const lines = [
    '# Event sources',
    '',
    'Generated by `npm run events` from `data/config/events.json`. Do not edit by hand.',
    '',
    `The ${cards.length} event cards in \`public/data/events.json\` describe real events in the project's own words. No text is copied from the sources below; each card links the pages it was written from. Events are shown for context only and never change a number in the simulation.`,
    '',
    'License: most sources are news or agency pages that state no license for reuse; they are linked, not copied.',
    '',
    '| Publisher | Label | URL | Card years | License |',
    '|---|---|---|---|---|',
    ...rows.map(
      (r) => `| ${esc(r.publisher)} | ${esc(r.label)} | ${r.url} | ${[...r.years].sort().join(', ')} | ${LICENSE_NOT_STATED} |`,
    ),
    '',
  ];
  return lines.join('\n');
}

export function buildEvents(read: ReadText): BuildResult {
  const errors: string[] = [];
  const fail = (): BuildResult => ({ ok: false, errors, cards: [], files: undefined });

  const table = parseJson<EventsTable>(read, TABLE_FILE, errors);
  const rows = parseJson<SourceRowsFile>(read, ROWS_FILE, errors);
  if (table === undefined || rows === undefined) return fail();

  for (const issue of checkTable(table, rows)) errors.push(`${issue.id} ${issue.field}: ${issue.message}`);
  if (errors.length > 0) return fail();

  const csv = read(DISCOUNT_RATE_FILE);
  if (csv === undefined) {
    errors.push(`${DISCOUNT_RATE_FILE}: file not found; run node scripts/download.ts macro (rate cards cannot be checked)`);
    return fail();
  }
  let rates: RateRow[];
  try {
    rates = parseDiscountRateCsv(csv);
  } catch (e) {
    errors.push(`${DISCOUNT_RATE_FILE}: ${e instanceof Error ? e.message : String(e)}`);
    return fail();
  }

  const majorIds = new Set(table.majorIds);
  const derived: EventCard[] = [];
  for (const row of table.events) {
    try {
      derived.push(deriveCard(row, { rates, majorIds }));
    } catch (e) {
      if (e instanceof RateMismatchError || e instanceof RangeError) errors.push(e.message);
      else throw e;
    }
  }
  if (errors.length > 0) return fail();
  const cards = sortCards(derived);

  const termsText = [read(BANNED_TERMS_FILE), read(EVENT_BANNED_TERMS_FILE)];
  const exemptText = read(BANNED_TERMS_EXEMPT_FILE) ?? '';
  if (termsText.some((t) => t === undefined)) {
    errors.push(`${BANNED_TERMS_FILE} or ${EVENT_BANNED_TERMS_FILE}: file not found`);
    return fail();
  }
  const terms = termsText.flatMap((t) => parseTermList(t as string));
  const exempt = parseTermList(exemptText);
  for (const c of cards) {
    for (const issue of [...checkCardText(c, terms, exempt), ...checkCardTextZh(c.zh, terms, exempt)]) errors.push(`${c.id} ${issue.field}: ${issue.message}`);
  }

  const file: EventsFile = { schemaVersion: 1, events: cards };
  for (const e of validateEventsFile(file)) errors.push(`${e.path} [${e.rule}]: ${e.message}`);

  const sources = renderEventSources(cards);
  for (const hit of checkBannedTerms(sources, terms, exempt)) errors.push(`${EVENT_SOURCES_OUT} line ${hit.line}: banned term "${hit.term}"`);
  if (errors.length > 0) return fail();

  return { ok: true, errors, cards, files: { events: serializeJson(file), sources } };
}

/** Builds and writes both outputs, or nothing. Returns the build result for the report. */
export function runEventBuild(read: ReadText, fsImpl: WriteFs = nodeFs, root: string = ROOT): BuildResult {
  const result = buildEvents(read);
  if (result.ok && result.files !== undefined) {
    writeAll(
      [
        { path: path.join(root, EVENTS_OUT), text: result.files.events },
        { path: path.join(root, EVENT_SOURCES_OUT), text: result.files.sources },
      ],
      fsImpl,
    );
  }
  return result;
}

/** Report lines printed on success (Requirement 8.7). */
export function reportLines(cards: readonly EventCard[]): string[] {
  const ids = (f: (c: EventCard) => boolean): string => cards.filter(f).map((c) => c.id).join(', ') || '(none)';
  return [
    `events.json: ${cards.length} cards`,
    `verified: true (${cards.filter((c) => c.verified).length}): ${ids((c) => c.verified)}`,
    `verified: false (${cards.filter((c) => !c.verified).length}): ${ids((c) => !c.verified)}`,
    `major (${cards.filter((c) => c.major).length}): ${ids((c) => c.major)}`,
    'rows left out: (none)',
  ];
}
