interface FieldRow {
  readonly field: string;
  readonly unit: string;
  readonly decimals: string;
  readonly sources: readonly string[];
}

function fieldTable(rows: readonly FieldRow[], registry: Registry): string[] {
  const body: string[][] = [];
  for (const row of rows) {
    for (const id of row.sources) {
      const s = registry.sources.get(id) as SourceEntry;
      const dataset = s.datasetEn === undefined ? s.dataset : `${s.dataset} (${s.datasetEn})`;
      body.push([row.field, row.unit, row.decimals, code(s.id), s.agency, dataset, s.url, years(s), s.license]);
    }
  }
  return table(['Field', 'Unit', 'Decimals', 'Source id', 'Agency', 'Dataset', 'URL', 'Years', 'License'], body);
}

