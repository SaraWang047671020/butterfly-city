/** Renders the full text of data/SOURCES.md. Throws a DataError when a referenced source or method is missing. */
export function renderSourcesDoc(input: SourcesDocInput): string {
  const registry = unionRegistry(input);
  checkReferences(input, registry);
  const blocks: string[][] = [
    ['# Data sources and methods'],
    section1(),
    section2(input),
    section3(input, registry),
    section4(registry),
    section5(registry),
    section6(input),
    section7(input),
    section8(input),
    section9(input),
  ];
  if (input.commute !== undefined) blocks.push(section10(input, input.commute));
  if (input.paramsPart1 !== undefined) blocks.push(section11(input, input.paramsPart1));
  return `${blocks.map((b) => b.join('\n')).join('\n\n')}\n`;
}

/** Step factory: renders state.sourcesDoc from the three output files, the notes and the committed tables. */
export function sourcesDocStep(readCommitted: CommittedReader = fsCommittedReader): Step {
  return {
    name: 'sources-doc',
    run(_ctx: BuildContext, state: BuildState) {
      const { districtsFile, historyFile, policyTrackFile } = state;
      if (districtsFile === undefined || historyFile === undefined || policyTrackFile === undefined) {
        throw new DataError('missing-step-output', 'output files', [
          'run the districts, history file and policy file steps before the SOURCES.md step',
        ]);
      }
      const { network, fareSlope, commuteCentroids, commuteSurvey } = state;
      const commute: CommuteDocInput | undefined =
        network !== undefined && fareSlope !== undefined && commuteCentroids !== undefined && commuteSurvey !== undefined
          ? {
              params: readCommuteParams(readCommitted),
              network,
              fares: fareSlope.pairing,
              centroids: commuteCentroids,
              survey: commuteSurvey,
              linkou: state.commuteLinkou,
            }
          : undefined;
      state.sourcesDoc = renderSourcesDoc({
        districtsFile,
        historyFile,
        policyTrackFile,
        commute,
        paramsPart1: state.paramsPart1,
        unitCostCases:
          state.paramsPart1 === undefined ? undefined : parseUnitCostCases(readCommitted(UNIT_COST_CASES_FILE), UNIT_COST_CASES_FILE),
        rentReferences: state.rentReferences,
        mrtBorderNotes: state.mrtBorderNotes,
        mrtComparableNotes: state.mrtComparableNotes,
        salePriceWindowCounts: state.salePriceWindowCounts,
        holdingTaxRates: parseHoldingTaxRates(readCommitted(HOLDING_TAX_TABLE), HOLDING_TAX_TABLE),
        commuterPassProducts: parseCommuterPassProducts(readCommitted(COMMUTER_PASS_TABLE), COMMUTER_PASS_TABLE),
        subleasePhases: parseSubleasePhases(readCommitted(SUBLEASE_TABLE), SUBLEASE_TABLE),
      });
    },
  };
}
