function linkouLimitation(n: NearestStationInfo | undefined): string {
  if (n === undefined) {
    return '- Linkou has no station in the model. Road speed is a gap value, so Linkou commute times may be over-estimated.';
  }
  const station = STATION_NAMES[n.stationId] ?? n.stationName;
  const line = LINE_NAMES[n.lineId] ?? n.lineId;
  return `- Linkou has no station in the model. Its residents reach the network by road at ${station} station (${n.stationId}, ${line}), about ${n.distanceKm.toFixed(2)} km from the Linkou population centre; for some destinations the road alone is faster. Road speed is a gap value, so Linkou commute times may be over-estimated.`;
}

// ---- text helpers ----

/** A table cell: no pipe, no line break. Empty text becomes `n/a`. */
function cell(text: string): string {
  const t = text.replace(/\r?\n/g, ' ').replace(/\|/g, '\\|').trim();
  return t === '' ? 'n/a' : t;
}

function code(text: string): string {
  return `\`${text}\``;
}

function table(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  return [
    `| ${header.join(' | ')} |`,
    `| ${header.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
  ];
}

function years(s: SourceEntry): string {
  return `${s.years[0]}–${s.years[1]}`;
}

function percent(part: number, total: number): string {
  return total === 0 ? '0.0' : ((part * 100) / total).toFixed(1);
}

function uniqueSorted(values: Iterable<string>): string[] {
  return [...new Set(values)].sort(codePointCompare);
}

// ---- registry assembly and checks ----

interface Registry {
  readonly sources: ReadonlyMap<string, SourceEntry>;
  readonly methods: ReadonlyMap<string, MethodEntry>;
}

function unionRegistry(input: SourcesDocInput): Registry {
  const sources = new Map<string, SourceEntry>();
  const methods = new Map<string, MethodEntry>();
  for (const file of [input.districtsFile, input.historyFile, input.policyTrackFile]) {
    for (const s of file.sources) if (!sources.has(s.id)) sources.set(s.id, s);
    for (const m of file.methods) if (!methods.has(m.id)) methods.set(m.id, m);
  }
  return { sources, methods };
}

function* historyRecords(file: HistoryFile): Generator<ValueRecord> {
  for (const indicator of file.indicators) {
    for (const records of Object.values(indicator.series as Record<string, readonly ValueRecord[]>)) yield* records;
  }
}

function* policyRecords(series: PolicySeries): Generator<TrackRecord> {
  for (const records of Object.values(series.series as Record<string, readonly TrackRecord[]>)) yield* records;
}

function policySeriesSources(series: PolicySeries): string[] {
  const ids = [...series.sources];
  const extra = new Set<string>();
  for (const r of policyRecords(series)) if (!series.sources.includes(r.source)) extra.add(r.source);
  return [...ids, ...[...extra].sort(codePointCompare)];
}

function sourceProblems(s: SourceEntry): string[] {
  const problems: string[] = [];
  const text = (name: string, v: unknown): void => {
    if (typeof v !== 'string' || v.trim() === '') problems.push(`source ${s.id}: ${name} is missing`);
  };
  text('agency', s.agency);
  text('dataset name', s.dataset);
  text('URL', s.url);
  text('license', s.license);
  const [a, b] = Array.isArray(s.years) ? s.years : [Number.NaN, Number.NaN];
  if (!Number.isInteger(a) || !Number.isInteger(b)) problems.push(`source ${s.id}: years covered are missing`);
  return problems;
}

/** Req 15.8: every referenced identifier has an entry and every source has its five attributes. */
function checkReferences(input: SourcesDocInput, registry: Registry): void {
  const problems: string[] = [];
  const needSource = (where: string, id: string): void => {
    if (!registry.sources.has(id)) problems.push(`${where}: source ${id} is not in the source registry`);
  };
  const needMethod = (where: string, id: string): void => {
    if (!registry.methods.has(id)) problems.push(`${where}: method ${id} is not in the method registry`);
  };
  for (const field of DISTRICT_FIELDS) {
    for (const id of input.districtsFile.provenance[field].sources) needSource(`districts.json ${field}`, id);
    const method = input.districtsFile.provenance[field].method;
    if (method !== undefined) needMethod(`districts.json ${field}`, method);
  }
  for (const ind of input.historyFile.indicators) {
    for (const id of ind.sources) needSource(`history.json ${ind.id}`, id);
  }
  const historyMethods = new Set<string>();
  for (const r of historyRecords(input.historyFile)) if (r.estimated) historyMethods.add(r.method);
  for (const id of historyMethods) needMethod('history.json', id);
  for (const s of input.policyTrackFile.policySeries) {
    for (const id of policySeriesSources(s)) needSource(`policy-track.json ${s.id}`, id);
    const used = new Set<string>();
    for (const r of policyRecords(s)) if (r.estimated) used.add(r.method);
    for (const id of used) needMethod(`policy-track.json ${s.id}`, id);
  }
  for (const m of registry.methods.values()) for (const id of m.inputs) needSource(`method ${m.id}`, id);
  for (const s of [...registry.sources.values()].sort((x, y) => codePointCompare(x.id, y.id))) {
    problems.push(...sourceProblems(s));
  }
  if (problems.length > 0) throw new DataError('sources-document', 'registry references', uniqueSorted(problems));
}

